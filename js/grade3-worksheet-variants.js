  const family = p => p.question.normalize('NFKC').replace(/\d+(?:[.,]\d+)*/g,'#').replace(/\s/g,'');
  function makeProblem(row, unit, section, index, term) {
    const [question,answer,...options] = row;
    const choices = [answer,...options];
    if(choices.length!==4 || new Set(choices).size!==4) throw Error('三年級新題選項有誤：'+question);
    const answerIndex=index%4;
    choices.splice(0,1);
    choices.splice(answerIndex,0,answer);
    return {
      id:'ws3-'+term+'-'+section.id+'-'+index,
      unitId:unit.id,sectionId:section.id,sectionTitle:section.title,
      question,options:choices,answerIndex,level:3,
      hint:'先圈出已知條件與要找的量，再用算式或圖檢查。',
      solutionSpeech:'答案是 '+answer+'。',taskKind:'情境與概念'
    };
  }
  function written(problem, mode, term) {
    const answer=problem.options[problem.answerIndex];
    const other=problem.options.find((_,i)=>i!==problem.answerIndex);
    const prompts=[
      ['訂正錯誤','有人把這題答成「'+other+'」。請改正，並在格子裡指出錯誤。'],
      ['驗證答案','有人把這題答成「'+answer+'」。請寫出驗證答案的方法。'],
      ['表達數量關係','先列出已知條件，再畫圖或寫算式，說明你怎麼找到答案。'],
      ['改編問題','先選原題答案，再改掉一個條件，讓原答案不再正確。寫出新問題及其答案。']
    ];
    const [taskKind,followup]=prompts[mode];
    return {...problem,id:problem.id+'-ws-'+term+'-'+mode,
      question:problem.question+' '+followup,options:mode<2?[]:problem.options,answerIndex:mode<2?-1:problem.answerIndex,
      answer:mode===3?'依學生改編的條件及解答核對':answer,taskKind,level:3,worksheetSource:problem,solutionSpeech:mode===3?'依學生改編的條件及解答核對。':problem.solutionSpeech||('答案是 '+answer+'。')};
  }
  function select(unit, section, problems, term, scopes) {
    if(!section) {
      const groups=unit.sections.map(s=>scopes(s));
      const output=[];
      for(let i=0;output.length<10;i++) {
        const group=groups[i%groups.length];
        const round=Math.floor(i/groups.length);
        output.push(group[(round*3+i%groups.length)%10]);
      }
      return {unit,section:null,problems:output};
    }
    const bank=term==='lower'?lower:upper;
    const rows=bank[unit.number-1][unit.sections.indexOf(section)];
    const authored=rows.map((row,i)=>makeProblem(row,unit,section,i+1,term));
    const source=problems.filter(p=>p.sectionId===section.id);
    const baseline=[];
    const seen=new Set(authored.map(family));
    const ordered=[...source].sort((a,b)=>Number(seen.has(family(a)))-Number(seen.has(family(b))));
    for(const p of ordered) {
      if(baseline.length>=(term==='lower'?2:4)) break;
      baseline.push(p);
      seen.add(family(p));
    }
    const numberNeeded=10-authored.length-baseline.length;
    const followups=Array.from({length:numberNeeded},(_,i)=>written(source[(3+i*2)%source.length],i%4,term));
    const pool=[...authored,...baseline,...followups];
    const order=term==='lower'?[0,4,6,1,7,2,5,8,3,9]:[0,2,6,3,7,1,4,8,5,9];
    return {unit,section,problems:order.map(i=>pool[i])};
  }
  function getWorksheet(data, unitId, sectionId, term) {
    const unit=data.units.find(item=>item.id===unitId);
    if(!unit) return null;
    const section=sectionId?unit.sections.find(item=>item.id===sectionId):null;
    if(sectionId&&!section) return null;
    return select(unit,section,data.practiceBank,term,s=>select(unit,s,data.practiceBank,term).problems);
  }
